"""Детерминированная починка запросов, которые пишет локальная модель."""
from onec_agent.agent import _fix_query


def test_iso_date_literals_become_datetime():
    assert _fix_query("ГДЕ Т.Дата >= '2026-09-01'") == "ГДЕ Т.Дата >= ДАТАВРЕМЯ(2026, 9, 1)"
    assert _fix_query("ГДЕ Т.Дата <= '2026-09-30T23:59:59'") == "ГДЕ Т.Дата <= ДАТАВРЕМЯ(2026, 9, 30, 23, 59, 59)"


def test_keyword_typos():
    assert "СГРУППИРОВАТЬ ПО" in _fix_query("ВЫБРАТЬ 1 ГРУППИРОВАТЬ ПО Т.А")
    assert _fix_query("ПОРЯДОК ПО Т.Дата ПОЗДНЕЕ") == "УПОРЯДОЧИТЬ ПО Т.Дата УБЫВ"
    assert _fix_query("УПОРЯДОЧИТЬ ПО Т.Дата DESC") == "УПОРЯДОЧИТЬ ПО Т.Дата УБЫВ"
    # Правильный текст не трогаем.
    ok = "ВЫБРАТЬ Т.Сумма ИЗ Документ.Р КАК Т УПОРЯДОЧИТЬ ПО Т.Дата УБЫВ"
    assert _fix_query(ok) == ok


def test_field_and_literal_fixes():
    assert _fix_query("ГДЕ Т.Удален = ЛОЖЬ") == "ГДЕ Т.ПометкаУдаления = ЛОЖЬ"
    assert _fix_query("ГДЕ Т.ЭтоГруппа = НЕТ И Т.Х = да") == "ГДЕ Т.ЭтоГруппа = ЛОЖЬ И Т.Х = ИСТИНА"
    # «НЕТто» — часть имени поля, не литерал.
    assert _fix_query("ВЫБРАТЬ Т.НЕТто ИЗ Т") == "ВЫБРАТЬ Т.НЕТто ИЗ Т"


def test_enum_synonym_to_name():
    text = "ГДЕ Т.Вид = ЗНАЧЕНИЕ(Перечисление.ВидСчетаФактурыВыставленного.На аванс)"
    assert _fix_query(text).endswith("ЗНАЧЕНИЕ(Перечисление.ВидСчетаФактурыВыставленного.НаАванс)")
    one_word = "ЗНАЧЕНИЕ(Перечисление.А.НаРеализацию)"
    assert _fix_query(one_word) == one_word


def test_dangling_grouping_removed():
    assert _fix_query("ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ Т СГРУППИРОВАТЬ ПО") == "ВЫБРАТЬ КОЛИЧЕСТВО(*) ИЗ Т"
